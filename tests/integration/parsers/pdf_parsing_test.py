"""C11 — PDF parsing: a file page is not a printed label (no database).

Every fixture is synthetic and generated by ``pdf_fixtures`` in this same
directory. None of them is a real book and none was downloaded: a downloaded
fixture could only be asserted against, never about — no test here could say
*which* file page carries *which* printed label if the bytes were somebody
else's.

The library under test is **pypdf** (imported by ``kb.catalog.parsers.pdf``,
version recorded in that module's ``PARSER_VERSION``). It is a real parse of
real bytes. There is no OCR in this card, and
``test_no_ocr_library_is_imported_by_the_parser`` proves that structurally
rather than asserting it in a comment.
"""

from __future__ import annotations

import ast
import io
import uuid
from pathlib import Path

import pdf_fixtures as fx
import pypdf
import pytest

from kb.catalog.parsers.pdf import (
    PARSER_NAME,
    PARSER_VERSION,
    fragment_row,
    parse_pdf,
    text_at_locator,
)
from kb.contracts.entities import Locator
from kb.contracts.enums import LocatorKind, ProcessingStatus

pytestmark = pytest.mark.integration

ROOT = Path(__file__).resolve().parents[3]
PARSER_SOURCE = ROOT / "src" / "kb" / "catalog" / "parsers" / "pdf.py"
COMMITTED = ROOT / "evals" / "fixtures" / "books"

SOURCE_ID = uuid.UUID("00000000-0000-4000-8000-0000000000c1")


# ------------------------------------------------- the two columns, kept apart


def test_the_parser_is_a_real_library_and_says_which_one():
    assert PARSER_NAME == "pypdf"
    assert PARSER_VERSION == pypdf.__version__
    # and the fixture really is parsed by that library, not by a stand-in
    reader = pypdf.PdfReader(io.BytesIO(fx.text_book_pdf()))
    assert len(reader.pages) == 4


def test_a_file_page_and_the_printed_label_on_it_are_different_values():
    """The invariant, stated as a test.

    ``text_book.pdf`` declares /PageLabels: file pages 1-2 are 'i','ii' and
    file pages 3-4 are '1','2'. File page 3 is printed page 1. Both numbers are
    real, both were read, and neither was derived from the other.
    """
    result = parse_pdf(fx.text_book_pdf(), source_id=SOURCE_ID)

    pairs = [(f.locator.file_page, f.locator.printed_label) for f in result.fragments]
    assert pairs == [(1, "i"), (2, "ii"), (3, "1"), (4, "2")]


def test_a_printed_label_is_never_copied_out_of_the_file_page_column():
    result = parse_pdf(fx.text_book_pdf(), source_id=SOURCE_ID)
    for fragment in result.fragments:
        assert fragment.locator.printed_label != str(fragment.locator.file_page)
    # the difference is real, not a coincidence of the fixture
    assert len({f.locator.file_page for f in result.fragments}) == 4
    assert len({f.locator.printed_label for f in result.fragments}) == 4


def test_a_document_that_declares_no_labels_gets_no_labels():
    """pypdf answers the page number when a document declares nothing.

    ``authored.pdf`` has no /PageLabels tree, so pypdf's own answer for its one
    page would be "1" — the file page wearing a label's clothes. Recording it
    would make the printed_label column corroborate file_page and hide exactly
    the disagreement the column exists to keep.
    """
    result = parse_pdf(fx.authored_pdf(), source_id=SOURCE_ID)
    assert [f.locator.file_page for f in result.fragments] == [1]
    assert [f.locator.printed_label for f in result.fragments] == [None]
    # pypdf really would have said "1" — the value was available and dropped
    reader = pypdf.PdfReader(io.BytesIO(fx.authored_pdf()))
    assert reader.page_labels == ["1"]


def test_every_pdf_fragment_is_a_file_page_and_nothing_else():
    result = parse_pdf(fx.text_book_pdf(), source_id=SOURCE_ID)
    for fragment in result.fragments:
        assert fragment.locator.kind is LocatorKind.PDF_FILE_PAGE
        assert fragment.locator.file_page is not None
        assert fragment.locator.chapter is None
        assert fragment.locator.paragraph is None


def test_the_ordinal_is_the_position_of_the_page_in_the_file():
    result = parse_pdf(fx.text_book_pdf(), source_id=SOURCE_ID)
    assert [f.ordinal for f in result.fragments] == [0, 1, 2, 3]
    assert [f.ordinal + 1 for f in result.fragments] == [
        f.locator.file_page for f in result.fragments
    ]


# --------------------------------------------------------- opening by locator


def test_a_source_opens_by_its_file_page():
    data = fx.text_book_pdf()
    result = parse_pdf(data, source_id=SOURCE_ID)
    page_three = result.fragments[2]

    opened = text_at_locator(data, page_three.locator)
    assert opened == page_three.text
    assert opened is not None
    assert opened.startswith("Chapter one begins on the page printed as 1")


def test_a_source_opens_by_its_printed_label_too():
    """Printed label "1" is file page 3 — the two must not be interchangeable."""
    data = fx.text_book_pdf()
    by_label = text_at_locator(data, Locator(kind=LocatorKind.PDF_PRINTED_LABEL, printed_label="1"))
    by_page = text_at_locator(data, Locator(kind=LocatorKind.PDF_FILE_PAGE, file_page=1))
    assert by_label is not None and by_page is not None
    assert by_label != by_page
    assert by_label.startswith("Chapter one begins")


def test_a_locator_that_names_nothing_returns_none():
    data = fx.text_book_pdf()
    assert text_at_locator(data, Locator(kind=LocatorKind.PDF_FILE_PAGE, file_page=99)) is None
    assert (
        text_at_locator(data, Locator(kind=LocatorKind.PDF_PRINTED_LABEL, printed_label="nope"))
        is None
    )
    assert (
        text_at_locator(data, Locator(kind=LocatorKind.PDF_PRINTED_LABEL, printed_label="")) is None
    )
    # an EPUB locator is not a PDF locator, and is not quietly reinterpreted
    assert text_at_locator(data, Locator(kind=LocatorKind.EPUB_CHAPTER, paragraph=1)) is None


def test_a_printed_label_several_pages_share_is_not_guessed():
    """Two pages labelled "A": answering either one would be a coin flip."""
    data = fx.build_pdf(
        [fx.PdfPage(lines=[f"page {n}"]) for n in range(1, 5)],
        page_labels=[
            fx.PageLabelRange(start=0, style="/A", first=1),
            fx.PageLabelRange(start=3, style="/A", first=1),
        ],
    )
    result = parse_pdf(data, source_id=SOURCE_ID)
    assert [(f.locator.file_page, f.locator.printed_label) for f in result.fragments] == [
        (1, "A"),
        (2, "B"),
        (3, "C"),
        (4, "A"),
    ]
    assert (
        text_at_locator(data, Locator(kind=LocatorKind.PDF_PRINTED_LABEL, printed_label="A"))
        is None
    )
    # an unambiguous label on the same file still resolves
    assert (
        text_at_locator(data, Locator(kind=LocatorKind.PDF_PRINTED_LABEL, printed_label="B"))
        == "page 2"
    )


