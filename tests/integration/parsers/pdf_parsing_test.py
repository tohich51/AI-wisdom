def test_an_encrypted_pdf_is_refused_rather_than_guessed():
    """Encrypted with pypdf's own writer — a real encrypted file, not a flag."""
    reader = pypdf.PdfReader(io.BytesIO(fx.authored_pdf()))
    writer = pypdf.PdfWriter()
    writer.append(reader)
    # S106: this is a password for a file this test builds itself, in a
    # temporary buffer that no password manager and no service ever sees. It
    # is a fixture value, not a credential, and it is inline on purpose so the
    # test says exactly what password the file was sealed with.
    writer.encrypt(user_password="not-empty", owner_password="not-empty")  # noqa: S106
    buffer = io.BytesIO()
    writer.write(buffer)

    result = parse_pdf(buffer.getvalue(), source_id=SOURCE_ID)
    assert result.processing is ProcessingStatus.FAILED
    assert [p.code for p in result.problems] == ["encrypted_pdf"]
    assert result.fragments == ()
    assert "guessed" in result.problems[0].detail


