def test_the_text_is_the_text_that_is_on_that_page():
    result = parse_pdf(fx.text_book_pdf(), source_id=SOURCE_ID)
    assert [f.text for f in result.fragments] == [
        "Title page of a synthetic book\nno author is written here",
        "Contents\nIntroduction .... 1",
        "Chapter one begins on the page printed as 1\nsecond line",
        "Chapter one continues on the page printed as 2",
    ]


def test_a_page_less_scan_becomes_needs_ocr_and_not_invented_text():
    """The card's central promise, on a real file with no text layer.

    ``scan.pdf`` draws a 2x2 grey image on each of its two pages and issues no
    text-drawing operator at all. There is no text in it, so none is produced:
    the result carries zero fragments, and the reason is visible per page.
    """
    result = parse_pdf(fx.scan_pdf(), source_id=SOURCE_ID)

    assert result.processing is ProcessingStatus.NEEDS_OCR
    assert result.needs_ocr is True
    assert result.fragments == ()
    assert result.page_count == 2  # the pages were counted, not skipped
    assert [(p.code, p.file_page) for p in result.problems] == [
        ("no_text_layer", 1),
        ("no_text_layer", 2),
    ]
    assert all("OCR" in p.detail for p in result.problems)
    # nothing anywhere in the result pretends to be the book's text
    assert not any(f.text for f in result.fragments)
    assert "A Scan" not in "".join(p.detail for p in result.problems)


def test_a_scan_page_never_becomes_a_fragment_row():
    """The database-facing half of the same promise, without a database.

    ``fragment_row`` is the only mapping this card offers to a caller, and on
    an empty result it can only produce nothing.
    """
    result = parse_pdf(fx.scan_pdf(), source_id=SOURCE_ID)
    assert [fragment_row(f) for f in result.fragments] == []


def test_a_half_scanned_document_is_partial_and_says_which_page_is_missing():
    data = fx.build_pdf(
        [
            fx.PdfPage(lines=["typed page one"]),
            fx.PdfPage(image=True),
            fx.PdfPage(lines=["typed page three"]),
        ],
        page_labels=[fx.PageLabelRange(start=0, style="/D", first=1)],
    )
    result = parse_pdf(data, source_id=SOURCE_ID)

    assert result.processing is ProcessingStatus.PARTIAL
    assert [f.locator.file_page for f in result.fragments] == [1, 3]
    assert [f.ordinal for f in result.fragments] == [0, 2]  # ordinals keep the page positions
    assert [(p.code, p.file_page) for p in result.problems] == [("no_text_layer", 2)]
    assert "image" in result.problems[0].detail


def test_no_ocr_library_is_imported_by_the_parser():
    """OCR is not implemented, and none is faked.

    An import walk of the parser module: no OCR/vision package is named, and the
    only third-party import is pypdf. This is the check that would fail if a
    later change quietly wired a "text extraction" fallback that guesses.
    """
    tree = ast.parse(PARSER_SOURCE.read_text(encoding="utf-8"))
    imported: set[str] = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            imported.update(alias.name.split(".")[0] for alias in node.names)
        elif isinstance(node, ast.ImportFrom) and node.module and node.level == 0:
            imported.add(node.module.split(".")[0])

    assert "pypdf" in imported
    assert not (imported & {"pytesseract", "tesserocr", "easyocr", "paddleocr", "ocrmypdf"})
    assert "fitz" not in imported and "pymupdf" not in imported

    # Call-shaped needles for the APIs an OCR package would be used through.
    # The first version of this test also banned the bare text "ocr(", which
    # failed on this module's own ``needs_ocr`` property — a textual ban wide
    # enough to hit a status name proves nothing about OCR.
    banned = ("image_to_string", "run_and_get_output", "do_ocr", "ocr_image", "tesseract")
    source = PARSER_SOURCE.read_text(encoding="utf-8").lower()
    for needle in banned:
        assert needle not in source, f"{needle!r} appears in the parser source"


