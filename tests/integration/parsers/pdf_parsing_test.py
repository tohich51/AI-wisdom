def test_the_committed_fixtures_are_exactly_what_this_module_generates():
    """The bytes under evals/ are synthetic and reproducible, or they are wrong."""
    for name, expected in fx.all_fixtures().items():
        committed = COMMITTED / name
        assert committed.exists(), f"{name} is missing from evals/fixtures/books/"
        assert committed.read_bytes() == expected, f"{name} drifted from its generator"


def test_the_synthetic_fixtures_are_never_referenced_by_the_product():
    """Acceptance: synthetic files are not preloaded into production.

    Nothing under src/, migrations/ or deploy/ may name the fixture directory
    or any committed fixture file. If a future card ships a preloaded book,
    this fails.
    """
    needles = ("evals/fixtures", "text_book.pdf", "scan.pdf", "booklet.epub", "scan.epub")
    for folder in ("src", "migrations", "deploy"):
        for path in (ROOT / folder).rglob("*"):
            if not path.is_file():
                continue
            body = path.read_text(encoding="utf-8", errors="ignore")
            for needle in needles:
                assert needle not in body, f"{path} references {needle}"
