def test_parsing_the_same_bytes_twice_produces_the_same_fragment_ids():
    """A re-parse must be recognisable as a re-parse, not a second document."""
    first = parse("basic.docx")
    second = parse("basic.docx")
    assert first.fragment_ids() == second.fragment_ids()
    assert len(set(first.fragment_ids())) == len(first.fragments)


def test_a_different_source_gets_different_fragment_ids():
    a = parse_docx(fixture_path("basic.docx"), source_id=uuid.uuid4())
    b = parse_docx(fixture_path("basic.docx"), source_id=uuid.uuid4())
    assert a.fragment_ids() != b.fragment_ids()


def test_ordinals_are_dense_and_ordered():
    result = parse("basic.docx")
    assert [f.ordinal for f in result.fragments] == list(range(len(result.fragments)))


def test_a_single_part_that_expands_a_thousandfold_is_refused_even_when_the_archive_does_not(
    tmp_path,
):
    """The per-part ratio check, proved on its own.

    The archive here expands to about 5:1 overall, so the whole-container check
    is quiet and only the per-part check can refuse it. Without a test like this
    one the per-part check could be deleted and every other test would still
    pass — redundancy that nobody has checked is not redundancy, it is an
    assumption.
    """
    padding = tmp_path / "padding.docx"
    padding.write_bytes(_zip_with_a_huge_part(with_incompressible_padding=True))

    import zipfile

    with zipfile.ZipFile(padding) as archive:
        infos = archive.infolist()
    total = sum(i.file_size for i in infos)
    compressed = sum(i.compress_size for i in infos)
    assert total / max(compressed, 1) < 50, "the container as a whole must look innocent"

    with pytest.raises(DocxArchiveError, match=r"expands \d+(\.\d+)?:1") as caught:
        parse_docx(padding, source_id=SOURCE)
    assert "word/document.xml" in str(caught.value), "the refusal must name the part"


# ------------------------------------------------------------ zip bomb helpers


def _zip_with_a_huge_part(with_incompressible_padding: bool = False) -> bytes:
    """A real package whose ``document.xml`` part is a deflate bomb.

    With ``with_incompressible_padding`` a 10 MiB member is added *stored*, which
    costs the overall ratio nothing (a stored part is already at 1:1) and so
    leaves the per-part check as the only thing that can object.
    """
    import io
    import zipfile

    from docx import Document as _Document

    document = _Document()
    document.add_paragraph("x" * 200_000)
    base = io.BytesIO()
    document.save(base)
    with zipfile.ZipFile(io.BytesIO(base.getvalue())) as original:
        members = {n: original.read(n) for n in original.namelist()}
    members["word/document.xml"] = b"<w:document>" + b"<!--" + b"\0" * 40_000_000 + b"-->"
    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer, "w", zipfile.ZIP_DEFLATED) as out:
        for name, payload in members.items():
            out.writestr(name, payload)
        if with_incompressible_padding:
            out.writestr("word/padding.bin", b"\0" * 10_000_000, compress_type=zipfile.ZIP_STORED)
    return buffer.getvalue()


def _zip_with_many_parts(count: int) -> bytes:
    import io
    import zipfile

    from docx import Document as _Document

    document = _Document()
    document.add_paragraph("hello")
    base = io.BytesIO()
    document.save(base)
    with zipfile.ZipFile(io.BytesIO(base.getvalue())) as original:
        members = {n: original.read(n) for n in original.namelist()}
    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer, "w", zipfile.ZIP_DEFLATED) as out:
        for name, payload in members.items():
            out.writestr(name, payload)
        for index in range(count):
            out.writestr(f"word/padding{index}.xml", "<x/>")
    return buffer.getvalue()


def _zip_without_document_xml() -> bytes:
    import io
    import zipfile

    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer, "w", zipfile.ZIP_DEFLATED) as out:
        out.writestr("[Content_Types].xml", "<Types/>")
    return buffer.getvalue()


def _zip_with_a_traversing_member() -> bytes:
    import io
    import zipfile

    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer, "w", zipfile.ZIP_DEFLATED) as out:
        out.writestr("[Content_Types].xml", "<Types/>")
        out.writestr("word/document.xml", "<document/>")
        out.writestr("../../etc/passwd", "root::0:0:::/:/bin/sh")
    return buffer.getvalue()
