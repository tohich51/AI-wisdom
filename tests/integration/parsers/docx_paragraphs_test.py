def test_a_good_document_passes_the_same_limits_it_is_meant_to_pass():
    payload = fixture_path("basic.docx").read_bytes()
    from_path = parse_docx_bytes(payload, source_id=SOURCE)
    from_disk = parse_docx(fixture_path("basic.docx"), source_id=SOURCE)
    assert [f.text for f in from_path.fragments] == [f.text for f in from_disk.fragments]
    assert from_path.fragment_ids() == from_disk.fragment_ids()


